export function getInterpolatedWhoForMonth(monthFloat, gender = 'girl') {
  const clamped = Math.max(0, Math.min(60, monthFloat));
  let lower = WHO_STANDARDS[0];
  let upper = WHO_STANDARDS[WHO_STANDARDS.length - 1];
  for (let i = 0; i < WHO_STANDARDS.length - 1; i++) {
    if (clamped >= WHO_STANDARDS[i].m && clamped <= WHO_STANDARDS[i + 1].m) {
      lower = WHO_STANDARDS[i];
      upper = WHO_STANDARDS[i + 1];
      break;
    }
  }
  const span = upper.m - lower.m || 1;
  const t = (clamped - lower.m) / span;
  const wKey = gender === 'boy' ? 'wB' : 'wG';
  const hKey = gender === 'boy' ? 'hB' : 'hG';
  const wMin = (lower[wKey][0] + (upper[wKey][0] - lower[wKey][0]) * t).toFixed(1);
  const wMax = (lower[wKey][2] + (upper[wKey][2] - lower[wKey][2]) * t).toFixed(1);
  const hMin = Math.round(lower[hKey][0] + (upper[hKey][0] - lower[hKey][0]) * t);
  const hMax = Math.round(lower[hKey][2] + (upper[hKey][2] - lower[hKey][2]) * t);
  return { weightRange: `${wMin}–${wMax} кг`, heightRange: `${hMin}–${hMax} см` };
}

