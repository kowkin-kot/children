function pickNonRepeating(arr, index, stride = 1) {
  if (!Array.isArray(arr) || arr.length === 0) return '';
  const len = arr.length;
  // Гарантируем, что шаг взаимно прост с длиной массива, чтобы проходить все элементы без зацикливания
  let step = stride % len || 1;
  const gcd = (a, b) => (b === 0 ? a : gcd(b, a % b));
  while (gcd(step, len) !== 1) {
    step = (step + 1) % len || 1;
  }
  return arr[(index * step) % len];
}

export function getWeekData(weekNum) {
  const w = Math.max(1, Math.min(260, Number(weekNum) || 1));
  const approxMonths = Math.floor((w - 1) / 4.33);
  const years = Math.floor(approxMonths / 12);
  const remMonths = approxMonths % 12;

  let ageContext = '';
  if (w <= 4) ageContext = 'Период новорождённости • 1-й месяц';
  else if (w <= 52) ageContext = `${approxMonths + 1}-й месяц жизни`;
  else if (years === 1) ageContext = remMonths === 0 ? '1 год' : `1 год ${remMonths} мес.`;
  else ageContext = remMonths === 0 ? `${years} года` : `${years} г. ${remMonths} мес.`;

  const isLeap = LEAP_WEEKS.includes(w);

  let prevMax = 0;
  let stage = WEEK_STAGES[WEEK_STAGES.length - 1];
  for (const s of WEEK_STAGES) {
    if (w <= s.maxWeek) {
      stage = s;
      break;
    }
    prevMax = s.maxWeek;
  }

  const localIdx = Math.max(0, w - prevMax - 1);
  const override = SPECIAL_WEEK_OVERRIDES[w] || null;

  const theme = stage.themes[localIdx % stage.themes.length];
  const title = override?.title
    || (isLeap ? `Неделя ${w}: скачок роста — ${theme.toLowerCase()}` : `Неделя ${w}: ${theme.toLowerCase()}`);
  const summary = stage.summaries[localIdx % stage.summaries.length];

  // Выбираем по 1 задаче из каждой из 5 категорий с разными взаимно простыми сдвигами,
  // чтобы комбинации не повторялись неделями
  const strides = { motor: 1, speech: 1, play: 2, care: 1, bond: 2 };
  const offsets = { motor: 0, speech: 1, play: 2, care: 3, bond: 4 };

  const checklistItems = CHECKLIST_CATEGORIES.map((cat) => {
    const pool = stage.pools[cat.key] || [];
    const text = pickNonRepeating(pool, localIdx + offsets[cat.key], strides[cat.key]);
    return { category: cat.label, text };
  }).filter(item => Boolean(item.text));

  // Для ключевых недель заменяем 5-й пункт на персональный акцент этой недели
  if (override?.bonusItem && checklistItems.length > 0) {
    checklistItems[checklistItems.length - 1] = override.bonusItem;
  }

  return {
    week: w,
    approxMonths,
    ageContext,
    isLeap,
    title,
    summary,
    sleepNorm: stage.sleepNorm,
    wakeWindow: stage.wakeWindow,
    feedInterval: stage.feedInterval,
    checklist: checklistItems.map(i => i.text),
    checklistItems
  };
}

