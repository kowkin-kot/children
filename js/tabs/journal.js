  const todayIso = getTodayIso();
  if (!store.selectedJournalDateIso || store.selectedJournalDateIso > todayIso) {
    store.selectedJournalDateIso = todayIso;
  }
  const selectedIso = store.selectedJournalDateIso;
  const { startMs, endMs } = parseIsoToLocalDayBounds(selectedIso);
  const isToday = selectedIso === todayIso;
  const now = Date.now();
