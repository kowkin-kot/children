export function saveManualLog(e) {
  if (e) e.preventDefault();
  const editId = document.getElementById('manual-log-id')?.value || '';
  const type = document.getElementById('manual-log-type')?.value || 'feeding';
  const subtype = document.getElementById('manual-log-subtype')?.value || 'general';
  const sleepTypeChoice = document.getElementById('manual-log-sleeptype')?.value || 'auto';
  const startVal = document.getElementById('manual-log-start')?.value;
  const endVal = document.getElementById('manual-log-end')?.value;
  const rawDur = Math.max(0, parseInt(document.getElementById('manual-log-duration')?.value || '0', 10) || 0);
  const rawNote = (document.getElementById('manual-log-note')?.value || '').trim();
  const isLiveTimer = !editId && Boolean(document.getElementById('manual-log-live-timer')?.checked) && ['feeding', 'feeding_solids', 'sleep', 'walk'].includes(type);

  const parsedStart = startVal ? new Date(startVal).getTime() : Date.now();
  const startTime = Number.isNaN(parsedStart) ? Date.now() : parsedStart;
  const warnEl = document.getElementById('manual-log-time-warning');

  if (isLiveTimer) {
    if (startTime > Date.now() + 60000) {
      if (warnEl) {
        warnEl.textContent = 'Время начала для таймера не может быть в будущем';
        warnEl.classList.remove('hidden');
      }
      return;
    }
    const timerKey = type === 'feeding_solids' ? 'feeding' : type;
    const timer = store.appState.timers[timerKey];
    let autoAwakeLive = null;
    if (timer) {
      timer.active = true;
      timer.startTime = startTime;
      if (timerKey === 'feeding') {
        timer.subtype = type === 'feeding_solids'
          ? 'solids'
          : (subtype === 'left' || subtype === 'right' || subtype === 'bottle' ? subtype : 'left');
      } else if (timerKey === 'sleep') {
        timer.sleepType = sleepTypeChoice === 'auto' ? detectSleepTypeByHour(startTime) : sleepTypeChoice;
        autoAwakeLive = maybeAutoInsertAwakeGapBeforeSleep(startTime);
        if (autoAwakeLive) {
          store.appState.journalLogs.sort((a, b) => (b.startTime || 0) - (a.startTime || 0));
        }
      }
    }
    closeModal('modal-manual-log');
    saveAppState();
    renderJournalTab();
    hooks.renderHereAndNowWidget();
    hooks.evaluateSmartNotifications();
    const timerLabels = { feeding: 'кормления', sleep: 'сна', walk: 'прогулки' };
    showToast(autoAwakeLive
      ? `Таймер сна запущен с ${formatClockHHMM(startTime)} • Добавлено бодрствование ${formatClockHHMM(autoAwakeLive.startTime)}–${formatClockHHMM(autoAwakeLive.endTime)}`
      : `Таймер ${timerLabels[timerKey] || ''} запущен с ${formatClockHHMM(startTime)}`);
    return;
  }

  let endTime = endVal ? new Date(endVal).getTime() : (startTime + rawDur * 60000);
  if (Number.isNaN(endTime)) endTime = startTime + rawDur * 60000;
  if (endTime < startTime) {
    if (warnEl) {
      warnEl.textContent = 'Время окончания не может быть раньше времени начала';
      warnEl.classList.remove('hidden');
    }
    return;
  }

  const durationMin = endVal ? Math.max(0, Math.round((endTime - startTime) / 60000)) : rawDur;
  const resolvedSleepType = type === 'sleep'
    ? (sleepTypeChoice === 'auto' ? detectSleepTypeByHour(startTime) : sleepTypeChoice)
    : undefined;

  const pumpLeftMl = type === 'pumping'
    ? Math.max(0, parseInt(document.getElementById('manual-log-pump-left')?.value || '0', 10) || 0)
    : 0;
  const pumpRightMl = type === 'pumping'
    ? Math.max(0, parseInt(document.getElementById('manual-log-pump-right')?.value || '0', 10) || 0)
    : 0;
  const pumpTotalMl = pumpLeftMl + pumpRightMl;

  let pumpingBaseTitle = 'Сцеживание';
  if (type === 'pumping' && pumpTotalMl > 0) {
    const lr = [];
    if (pumpLeftMl > 0) lr.push(`Л: ${pumpLeftMl}`);
    if (pumpRightMl > 0) lr.push(`П: ${pumpRightMl}`);
    pumpingBaseTitle = `Сцеживание: ${pumpTotalMl} мл${lr.length ? ` (${lr.join(' • ')})` : ''}`;
  }

  const defaultLabels = {
    feeding: subtype === 'left' ? 'Левая грудь' : subtype === 'right' ? 'Правая грудь' : subtype === 'bottle' ? 'Бутылочка' : 'Кормление',
    feeding_solids: 'Прикорм',
    sleep: resolvedSleepType === 'night' ? 'Ночной сон' : 'Дневной сон',
    awake: 'Бодрствование',
    walk: 'Прогулка',
    diaper_wet: 'Мокрый подгузник',
    diaper_dirty: 'Грязный подгузник',
    bath: 'Купание',
    vitamin: 'Витамин D3',
    pumping: pumpingBaseTitle
  };

  const generatedTitle = `${defaultLabels[type] || 'Событие'}${durationMin > 0 ? ` (${formatMinutesHuman(durationMin)})` : ''}`;
  let title = rawNote || generatedTitle;
  let autoAwakeAdded = null;

  if (editId) {
    const idx = store.appState.journalLogs.findIndex(l => l.id === editId);
    if (idx !== -1) {
      const prevLog = store.appState.journalLogs[idx];
      const prevBounds = getLogTimeBounds(prevLog);
      const prevDisplayTitle = formatDisplayLogTitle(prevLog);
      const noteUnchanged = prevLog && (rawNote === prevLog.title || rawNote === prevDisplayTitle);

      // Если пользователь изменил время/длительность/тип, но не менял текст вручную — обновляем заголовок и длительность в скобках
      if (noteUnchanged) {
        if (type === 'pumping' && pumpTotalMl > 0) {
          title = generatedTitle;
        } else if (PURE_AUTO_TITLE_RE.test(rawNote)) {
          title = generatedTitle;
        } else if (TRAILING_DURATION_RE.test(rawNote)) {
          const prefix = rawNote.replace(TRAILING_DURATION_RE, '').trim();
          title = durationMin > 0 ? `${prefix} (${formatMinutesHuman(durationMin)})` : prefix;
        }
      }

      const updatedLog = {
        ...prevLog,
        type,
        subtype: type === 'feeding' ? subtype : (type === 'feeding_solids' ? 'solids' : undefined),
        sleepType: resolvedSleepType,
        title,
        startTime,
        endTime,
        durationMin,
        ...(type === 'pumping' ? { leftMl: pumpLeftMl, rightMl: pumpRightMl, totalMl: pumpTotalMl } : {}),
        autoGenerated: type === 'awake' ? false : prevLog.autoGenerated
      };
      store.appState.journalLogs[idx] = updatedLog;
      reconcileAutoAwakeAfterEdit(updatedLog, prevBounds);
    }
  } else {
    const newId = 'log_' + Date.now();
    store.appState.journalLogs.unshift({
      id: newId,
      type,
      subtype: type === 'feeding' ? subtype : (type === 'feeding_solids' ? 'solids' : undefined),
      sleepType: resolvedSleepType,
      title,
      startTime,
      endTime,
      durationMin,
      ...(type === 'pumping' && pumpTotalMl > 0 ? { leftMl: pumpLeftMl, rightMl: pumpRightMl, totalMl: pumpTotalMl } : {}),
      author: getCurrentCaregiverName()
    });

    if (type === 'sleep') {
      autoAwakeAdded = maybeAutoInsertAwakeGapBeforeSleep(startTime, newId);
    } else if (type !== 'awake') {
      autoAwakeAdded = maybeAutoInsertAwakeGapBeforeNextSleep(endTime, newId);
    }
  }

  const dStart = new Date(startTime);
  store.selectedJournalDateIso = `${dStart.getFullYear()}-${String(dStart.getMonth() + 1).padStart(2, '0')}-${String(dStart.getDate()).padStart(2, '0')}`;

  store.appState.journalLogs.sort((a, b) => (b.startTime || 0) - (a.startTime || 0));
  closeModal('modal-manual-log');
  saveAppState();
  renderJournalTab();
  hooks.renderHereAndNowWidget();
  hooks.evaluateSmartNotifications();
  if (editId) {
    showToast('Запись обновлена');
  } else if (autoAwakeAdded) {
    showToast(`Запись добавлена • Автоматически добавлено бодрствование ${formatClockHHMM(autoAwakeAdded.startTime)}–${formatClockHHMM(autoAwakeAdded.endTime)}`);
  } else {
    showToast('Запись добавлена в журнал');
  }
}

