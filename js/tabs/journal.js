export function toggleTimer(kind) {
  const now = Date.now();
  const timer = store.appState.timers[kind];
  if (!timer) return;

  if (!timer.active) {
    timer.active = true;
    timer.startTime = now;
    let autoAwake = null;
    if (kind === 'sleep') {
      timer.sleepType = detectSleepTypeByHour(now);
      autoAwake = maybeAutoInsertAwakeGapBeforeSleep(now);
      if (autoAwake) {
        store.appState.journalLogs.sort((a, b) => (b.startTime || 0) - (a.startTime || 0));
      }
    }
    saveAppState();
    if (autoAwake) {
      renderJournalTab();
    } else {
      renderJournalTimersUI();
    }
    hooks.renderHereAndNowWidget();
    hooks.evaluateSmartNotifications();
    if (kind === 'sleep' && autoAwake) {
      showToast(`Таймер сна запущен • Добавлено бодрствование ${formatClockHHMM(autoAwake.startTime)}–${formatClockHHMM(autoAwake.endTime)}`);
    } else {
      showToast(kind === 'feeding' ? 'Таймер кормления запущен' : kind === 'sleep' ? 'Таймер сна запущен' : 'Таймер прогулки запущен');
    }
  } else {
    const startTs = timer.startTime || now;
    const durationMin = Math.max(1, Math.round((now - startTs) / 60000));
    timer.active = false;
    timer.startTime = null;
    let autoAwake = null;

    if (kind === 'feeding') {
      const sub = timer.subtype || 'left';
      let title = 'Кормление';
      let logType = 'feeding';
      if (sub === 'left') {
        title = `Левая грудь (${durationMin} мин)`;
        timer.subtype = 'right';
      } else if (sub === 'right') {
        title = `Правая грудь (${durationMin} мин)`;
        timer.subtype = 'left';
      } else if (sub === 'bottle') {
        const content = document.getElementById('feeding-bottle-content')?.value || 'Смесь';
        const ml = document.getElementById('feeding-amount-input')?.value || '';
        title = `Бутылочка: ${content}${ml ? `, ${ml} мл` : ''} (${durationMin} мин)`;
      } else if (sub === 'solids') {
        logType = 'feeding_solids';
        title = buildSolidsSummary();
      }
      store.appState.journalLogs.unshift({
        id: 'log_' + now,
        type: logType,
        subtype: sub,
        title,
        startTime: startTs,
        endTime: now,
        durationMin,
        author: getCurrentCaregiverName()
      });
    } else if (kind === 'sleep') {
      const sType = timer.sleepType || detectSleepTypeByHour(startTs);
      const sLabel = sType === 'night' ? 'Ночной сон' : 'Дневной сон';
      const newSleepId = 'log_' + now;
      store.appState.journalLogs.unshift({
        id: newSleepId,
        type: 'sleep',
        sleepType: sType,
        title: `${sLabel} (${formatMinutesHuman(durationMin)})`,
        startTime: startTs,
        endTime: now,
        durationMin,
        author: getCurrentCaregiverName()
      });
      autoAwake = maybeAutoInsertAwakeGapBeforeSleep(startTs, newSleepId);
    } else if (kind === 'walk') {
      store.appState.journalLogs.unshift({
        id: 'log_' + now,
        type: 'walk',
        title: `Прогулка (${formatMinutesHuman(durationMin)})`,
        startTime: startTs,
        endTime: now,
        durationMin,
        author: getCurrentCaregiverName()
      });
    }

    store.appState.journalLogs.sort((a, b) => (b.startTime || 0) - (a.startTime || 0));
    store.selectedJournalDateIso = getTodayIso();
    saveAppState();
    renderJournalTab();
    hooks.renderHereAndNowWidget();
    hooks.evaluateSmartNotifications();
    hooks.renderNightMode();
    showToast(autoAwake
      ? `Сон сохранён • Добавлено бодрствование ${formatClockHHMM(autoAwake.startTime)}–${formatClockHHMM(autoAwake.endTime)}`
      : 'Запись сохранена в журнал');
  }
}

