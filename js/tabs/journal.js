const MAX_AUTO_AWAKE_GAP_MIN = 480; // до 8 часов между последним событием и сном

function getLogTimeBounds(log) {
  const start = Number(log?.startTime) || 0;
  const durMin = Number(log?.durationMin) || 0;
  const end = Number(log?.endTime) || (start + durMin * 60000);
  return { start, end: Math.max(start, end) };
}

function hasOverlapInGap(logs, gapStart, gapEnd, excludeId = '') {
  for (const log of logs) {
    if (!log || (excludeId && log.id === excludeId)) continue;
    const { start, end } = getLogTimeBounds(log);
    if (!start) continue;
    // Пересечение интервала (gapStart, gapEnd) с другим событием
    if (start < gapEnd && end > gapStart) return true;
    // Точечное событие (duration = 0) строго внутри промежутка
    if (start === end && start > gapStart && start < gapEnd) return true;
  }
  return false;
}

function createAutoAwakeLog(gapStart, gapEnd) {
  const gapMin = Math.round((gapEnd - gapStart) / 60000);
  if (gapEnd <= gapStart || gapMin < 1 || gapMin > MAX_AUTO_AWAKE_GAP_MIN) {
    return null;
  }
  const awakeLog = {
    id: `log_awake_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    type: 'awake',
    title: `Бодрствование (${formatMinutesHuman(gapMin)})`,
    startTime: gapStart,
    endTime: gapEnd,
    durationMin: gapMin,
    autoGenerated: true
  };
  store.appState.journalLogs.unshift(awakeLog);
  return awakeLog;
}

// Автоматически добавляет «Бодрствование» между предыдущим событием и началом сна (например, кормление 10:00–10:15 и сон с 10:20 -> бодрствование 10:15–10:20)
function maybeAutoInsertAwakeGapBeforeSleep(sleepStart, excludeSleepId = '') {
  const logs = store.appState.journalLogs || [];
  if (!sleepStart || logs.length === 0) return null;

  let latestPrevEnd = 0;
  let latestPrevLogs = [];

  for (const log of logs) {
    if (!log || (excludeSleepId && log.id === excludeSleepId)) continue;
    const { start, end } = getLogTimeBounds(log);
    if (!start) continue;
    // Если какое-то событие уже идёт в момент начала сна (например, сон на прогулке), промежутка нет
    if (start < sleepStart && end > sleepStart) return null;
    if (end <= sleepStart && end > 0) {
      if (end > latestPrevEnd) {
        latestPrevEnd = end;
        latestPrevLogs = [log];
      } else if (end === latestPrevEnd) {
        latestPrevLogs.push(log);
      }
    }
  }

  if (!latestPrevEnd || latestPrevEnd >= sleepStart) return null;
  // Не наслаиваем автоматическое бодрствование, если непосредственно до этого уже отмечено бодрствование
  if (latestPrevLogs.some(l => l.type === 'awake')) return null;
  if (hasOverlapInGap(logs, latestPrevEnd, sleepStart, excludeSleepId)) return null;

  return createAutoAwakeLog(latestPrevEnd, sleepStart);
}

// Если пользователь добавил активность (например, кормление 10:00–10:15), а сон с 10:20 уже есть в журнале, также заполняем промежуток бодрствованием
function maybeAutoInsertAwakeGapBeforeNextSleep(activityEnd, excludeActivityId = '') {
  const logs = store.appState.journalLogs || [];
  if (!activityEnd || logs.length === 0) return null;

  let nextEvent = null;
  let nextStart = Infinity;

  for (const log of logs) {
    if (!log || (excludeActivityId && log.id === excludeActivityId)) continue;
    const { start, end } = getLogTimeBounds(log);
    if (!start) continue;
    // Если другое событие уже перекрывает момент окончания активности, промежутка нет
    if (start < activityEnd && end > activityEnd) return null;
    if (start > activityEnd && start < nextStart) {
      nextStart = start;
      nextEvent = log;
    }
  }

  if (!nextEvent || nextEvent.type !== 'sleep') return null;
  if (hasOverlapInGap(logs, activityEnd, nextStart, excludeActivityId)) return null;

  return createAutoAwakeLog(activityEnd, nextStart);
}

const PURE_AUTO_TITLE_RE = /^(Дневной сон|Ночной сон|Сон|Бодрствование|Прогулка|Левая грудь|Правая грудь|Бутылочка|Кормление|Прикорм|Купание|Сцеживание|Мокрый подгузник|Грязный подгузник|Витамин D3)(?:\s*\(\s*(?:\d+\s*ч(?:\s*\d+\s*мин)?|\d+\s*мин)\s*\))?$/;
const TRAILING_DURATION_RE = /\s*\(\s*(?:\d+\s*ч(?:\s*\d+\s*мин)?|\d+\s*мин)\s*\)$/;

function formatDisplayLogTitle(log) {
  const rawTitle = String(log?.title || '').trim();
  if (!rawTitle) return 'Событие';
  const { start, end } = getLogTimeBounds(log);
  const actualDurMin = end > start ? Math.round((end - start) / 60000) : (Number(log?.durationMin) || 0);
  if (actualDurMin > 0 && PURE_AUTO_TITLE_RE.test(rawTitle)) {
    const baseLabel = rawTitle.replace(TRAILING_DURATION_RE, '').trim();
    return `${baseLabel} (${formatMinutesHuman(actualDurMin)})`;
  }
  return rawTitle;
}

// После ручного редактирования записи обновляет/обрезает/удаляет конфликтующие авто-записи «Бодрствование», чтобы они не перекрывали изменённый сон на графике
function reconcileAutoAwakeAfterEdit(editedLog, prevBounds) {
  if (!editedLog || editedLog.type === 'awake') return;
  const logs = store.appState.journalLogs || [];
  const { start: eStart, end: eEnd } = getLogTimeBounds(editedLog);
  const oldStart = prevBounds?.start || eStart;
  const oldEnd = prevBounds?.end || eEnd;
  const toRemoveIds = new Set();

  for (const log of logs) {
    if (!log || log.id === editedLog.id || log.type !== 'awake' || !log.autoGenerated) continue;
    const { start: aStart, end: aEnd } = getLogTimeBounds(log);

    // 1. Авто-бодрствование, которое заканчивалось ровно на прежнем начале этого сна — подтягиваем к новому началу сна
    if (editedLog.type === 'sleep' && Math.abs(aEnd - oldStart) <= 60000 && aStart < eStart) {
      const nextDur = Math.round((eStart - aStart) / 60000);
      if (nextDur >= 1 && nextDur <= MAX_AUTO_AWAKE_GAP_MIN) {
        log.endTime = eStart;
        log.durationMin = nextDur;
        log.title = `Бодрствование (${formatMinutesHuman(nextDur)})`;
        continue;
      } else {
        toRemoveIds.add(log.id);
        continue;
      }
    }

    // 2. Авто-бодрствование, которое начиналось ровно на прежнем окончании этой записи — подтягиваем к новому окончанию
    if (Math.abs(aStart - oldEnd) <= 60000 && eEnd < aEnd) {
      const nextDur = Math.round((aEnd - eEnd) / 60000);
      if (nextDur >= 1 && nextDur <= MAX_AUTO_AWAKE_GAP_MIN) {
        log.startTime = eEnd;
        log.durationMin = nextDur;
        log.title = `Бодрствование (${formatMinutesHuman(nextDur)})`;
        continue;
      } else {
        toRemoveIds.add(log.id);
        continue;
      }
    }

    // 3. Общее пересечение: обрезаем или удаляем авто-бодрствование, попавшее под отредактированную запись
    if (aStart < eEnd && aEnd > eStart) {
      if (eStart <= aStart && eEnd >= aEnd) {
        toRemoveIds.add(log.id);
      } else if (eStart <= aStart && eEnd < aEnd) {
        const nextDur = Math.round((aEnd - eEnd) / 60000);
        if (nextDur >= 1) {
          log.startTime = eEnd;
          log.durationMin = nextDur;
          log.title = `Бодрствование (${formatMinutesHuman(nextDur)})`;
        } else {
          toRemoveIds.add(log.id);
        }
      } else if (eStart > aStart && eEnd >= aEnd) {
        const nextDur = Math.round((eStart - aStart) / 60000);
        if (nextDur >= 1) {
          log.endTime = eStart;
          log.durationMin = nextDur;
          log.title = `Бодрствование (${formatMinutesHuman(nextDur)})`;
        } else {
          toRemoveIds.add(log.id);
        }
      } else {
        // Отредактированная запись оказалась строго внутри авто-бодрствования — удаляем устаревшее авто-бодрствование
        toRemoveIds.add(log.id);
      }
    }
  }

  if (toRemoveIds.size > 0) {
    store.appState.journalLogs = logs.filter(l => !toRemoveIds.has(l.id));
  }
}

