export function readCaregiverName(login) {
  try {
    const raw = localStorage.getItem(LOCAL_CAREGIVER_KEY);
    if (!raw) return 'Мама';
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed === 'object') {
      const val = (login && parsed[login]) || parsed._default || 'Мама';
      const clean = String(val).trim();
      return clean ? clean.slice(0, 32) : 'Мама';
    }
    return 'Мама';
  } catch (_) {
    return 'Мама';
  }
}

